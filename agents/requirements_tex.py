#!/usr/bin/env python3
"""requirements_tex.py [--trm] [requirements.txt]:  the firmware requirements as a LaTeX table (qaqc_requirements.tex),
for the appendix of qaqc.tex;  with --trm, in the TRM's style for its appendix (trm/firmware_requirements.tex).
Source:  pacman-firmware docs/requirements.txt (default:  the cowork checkout next to this repo).  Run it again
whenever requirements.txt changes."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARGS = [a for a in sys.argv[1:] if a != "--trm"]
SRC = Path(ARGS[0]) if ARGS else HERE / "../../pacman-firmware/docs/requirements.txt"


def tex(s):
    for c in "&%$#_{}":
        s = s.replace(c, "\\" + c)
    return re.sub(r"\s+", " ", s)


def requirements():
    """[(id, level, where, text)], as report.py in pacman-firmware ghdl/agents reads them"""
    out = []
    for line in SRC.read_text().splitlines():
        m = re.match(r"^([A-Z]+(?:-\d+(?:\.\d+)?)?)\s+(sim\+hw|sim)?\s*(.*)$", line)
        if m and ((m.group(1).isalpha() and len(m.group(1)) <= 4) or "-" in m.group(1)) and m.group(3):
            rid, where, text = m.groups()
            level = 0 if rid.isalpha() else (1 if "." not in rid else 2)
            out.append([rid, level, where or "", text.strip()])
        elif out and line.startswith(" " * 17) and line.strip():
            out[-1][3] += " " + line.strip()
    return out


HEAD = r"""{\small
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.09\linewidth}>{\raggedright\arraybackslash}p{0.07\linewidth}>{\raggedright\arraybackslash}p{0.77\linewidth}@{}}
\toprule
ID & Where & Requirement \\
\midrule
\endhead
"""
TAIL = r"""\bottomrule
\end{longtable}
}
"""


TRM_HEAD = r"""{\small
\begin{longtable}{l l >{\raggedright\arraybackslash}p{13.0cm}}
\caption{\label{tbl:requirements} Firmware requirements.}\\
ID & Where & Requirement \\
\hline
\endfirsthead
ID & Where & Requirement \\
\hline
\endhead
"""
TRM_TAIL = r"""\end{longtable}
}
"""


def trm():
    """the same table in the TRM's style (no booktabs), for trm/firmware_requirements.tex"""
    rows = []
    for rid, level, where, text in requirements():
        if level == 0:
            rows.append(r"\multicolumn{3}{l}{\rule{0pt}{14pt}\textbf{%s:  %s}} \\" % (rid, tex(text)))
        elif level == 1:
            rows.append(r"\texttt{%s} & \multicolumn{2}{>{\raggedright\arraybackslash}p{14.6cm}}{\emph{%s}} \\"
                        % (rid, tex(text)))
        else:
            rows.append(r"\texttt{%s} & %s & %s \\" % (rid, where, tex(text)))
    out = HERE / "../trm/firmware_requirements.tex"
    out.write_text("% generated by agents/requirements_tex.py --trm from pacman-firmware docs/requirements.txt:  "
                   "do not edit\n" + TRM_HEAD + "\n".join(rows) + "\n" + TRM_TAIL)
    print("%s:  %d lines" % (out.name, len(rows)))


def main():
    if "--trm" in sys.argv:
        trm()
        return
    rows = []
    for rid, level, where, text in requirements():
        if level == 0:
            rows.append(r"\addlinespace[4pt]\multicolumn{3}{@{}l}{\textbf{%s:  %s}} \\" % (rid, tex(text)))
        elif level == 1:
            rows.append(r"\texttt{%s} & \multicolumn{2}{>{\raggedright\arraybackslash}p{\dimexpr0.84\linewidth+2\tabcolsep}@{}}{\emph{%s}} \\"
                        % (rid, tex(text)))
        else:
            rows.append(r"\texttt{%s} & %s & %s \\" % (rid, where, tex(text)))
    out = HERE / "qaqc_requirements.tex"
    out.write_text("% generated by requirements_tex.py from pacman-firmware docs/requirements.txt:  do not edit\n"
                   + HEAD + "\n".join(rows) + "\n" + TAIL)
    print("%s:  %d lines" % (out.name, len(rows)))


if __name__ == "__main__":
    main()
