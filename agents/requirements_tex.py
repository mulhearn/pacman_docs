#!/usr/bin/env python3
"""requirements_tex.py [requirements.txt]:  the firmware requirements as a LaTeX table (qaqc_requirements.tex), for
the appendix of qaqc.tex.  Source:  pacman-firmware docs/requirements.txt (default:  the cowork checkout next
to this repo).  Run it again whenever requirements.txt changes."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "../../pacman-firmware/docs/requirements.txt"


def tex(s):
    for c in "&%$#_{}":
        s = s.replace(c, "\\" + c)
    return re.sub(r"\s+", " ", s)


def requirements():
    """[(id, level, where, text)], as report.py in pacman-firmware ghdl/agents reads them"""
    out = []
    for line in SRC.read_text().splitlines():
        m = re.match(r"^([A-Z]+(?:-\d+(?:\.\d+)?)?)\s+(sim\+hw|sim)?\s*(.*)$", line)
        if m and ((m.group(1).isalpha() and len(m.group(1)) <= 4) or "-" in m.group(1)) and m.group(3):
            rid, where, text = m.groups()
            level = 0 if rid.isalpha() else (1 if "." not in rid else 2)
            out.append([rid, level, where or "", text.strip()])
        elif out and line.startswith(" " * 17) and line.strip():
            out[-1][3] += " " + line.strip()
    return out


HEAD = r"""{\small
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.09\linewidth}>{\raggedright\arraybackslash}p{0.07\linewidth}>{\raggedright\arraybackslash}p{0.77\linewidth}@{}}
\toprule
ID & Where & Requirement \\
\midrule
\endhead
"""
TAIL = r"""\bottomrule
\end{longtable}
}
"""


def main():
    rows = []
    for rid, level, where, text in requirements():
        if level == 0:
            rows.append(r"\addlinespace[4pt]\multicolumn{3}{@{}l}{\textbf{%s:  %s}} \\" % (rid, tex(text)))
        elif level == 1:
            rows.append(r"\texttt{%s} & \multicolumn{2}{>{\raggedright\arraybackslash}p{\dimexpr0.84\linewidth+2\tabcolsep}@{}}{\emph{%s}} \\"
                        % (rid, tex(text)))
        else:
            rows.append(r"\texttt{%s} & %s & %s \\" % (rid, where, tex(text)))
    out = HERE / "qaqc_requirements.tex"
    out.write_text("% generated by requirements_tex.py from pacman-firmware docs/requirements.txt:  do not edit\n"
                   + HEAD + "\n".join(rows) + "\n" + TAIL)
    print("%s:  %d lines" % (out.name, len(rows)))


if __name__ == "__main__":
    main()
